function [x, names] = window_features(D, ts, W, Wb, P)
% WINDOW_FEATURES  Features of one measurement window, relative to the window before it.
%   [X, NAMES] = WINDOW_FEATURES(D, TS, W, WB, P) uses the dataset case D
%   (see MAKE_DATASET). The window runs from TS to TS + W seconds after the
%   start of D's record; the baseline is the WB seconds before TS. Every
%   feature is a change from the baseline, so the operating point itself is
%   not a feature. All inputs are quantities an inverter measures at its own
%   terminals: PCC voltage, its own current, its PLL frequency, DC-link
%   voltage and its d/q currents. P supplies the ratings (P.Sn, P.Ipk, P.Vpk).
%
%   Fundamental components come from a least-squares fit of the voltage and
%   current space vectors to a positive- and a negative-sequence phasor at
%   the baseline frequency; what the fit leaves over is the distortion.
%   Zh_ratio compares the distortion impedance (residual voltage over
%   residual current) with the baseline's: when the grid is lost the PCC
%   impedance the inverter's ripple current sees rises from the grid's to
%   the load's, while ordinary events leave it nearly unchanged. df_max_n
%   and dV_max_n are scaled by the baseline's own fluctuation, so a noisier
%   weak grid does not look like an event.
names = {'dV_mean', 'dV_max', 'df_end', 'df_max', 'rocof_fit', 'rocof_peak', ...
         'phase_jump', 'dV_pos', 'dV_neg', 'dI_pos', 'dI_neg', 'dP', 'dQ', 'P_slope', ...
         'dTHD_v', 'dTHD_i', 'dVdc_max', 'dId_max', 'dIq_max', 'Zh_ratio', 'df_max_n', 'dV_max_n'};
fs = D.fs; fw = D.fsWave;
b  = (round((ts - Wb)*fs):round(ts*fs)) + 1;          % 1 kHz signals
w  = (round(ts*fs):round((ts + W)*fs)) + 1;
bw = (round((ts - Wb)*fw):round(ts*fw)) + 1;           % 10 kHz waveforms
ww = (round(ts*fw):round((ts + W)*fw)) + 1;

V = double(D.Vpcc_rms); f = double(D.freq);
Vb = mean(V(b)); fb = mean(f(b));
tw = (0:numel(w) - 1)'/fs;
pf = [tw ones(size(tw))] \ f(w);

v = double(D.Vabc); i = double(D.Igrid);
vc = ((2*v(:,1) - v(:,2) - v(:,3))/3 + 1j*(v(:,2) - v(:,3))/sqrt(3))/P.Vpk;   % space vectors, pu
ic = ((2*i(:,1) - i(:,2) - i(:,3))/3 + 1j*(i(:,2) - i(:,3))/sqrt(3))/P.Ipk;
om = 2*pi*fb;
fit = @(z, k) [exp(1j*om*(k - 1)'/fw) exp(-1j*om*(k - 1)'/fw)] \ z(k);
res = @(z, k, c) sqrt(mean(abs(z(k) - [exp(1j*om*(k - 1)'/fw) exp(-1j*om*(k - 1)'/fw)]*c).^2));
vB = fit(vc, bw); vW = fit(vc, ww);
iB = fit(ic, bw); iW = fit(ic, ww);

% inverter output power (Igrid is positive into the inverter), pu of rating
s = -1.5*P.Vpk*P.Ipk*vc.*conj(ic)/P.Sn;
pB = mean(real(s(bw))); pW = mean(real(s(ww)));
qB = mean(-imag(s(bw))); qW = mean(-imag(s(ww)));
tpw = (0:numel(ww) - 1)'/fw;
pp = [tpw ones(size(tpw))] \ real(s(ww));

dc = double(D.VDC); id = double(D.ID); iq = double(D.IQ);
x = [ ...
    mean(V(w)) - Vb, ...
    max(abs(V(w) - Vb)), ...
    f(w(end)) - fb, ...
    max(abs(f(w) - fb)), ...
    pf(1), ...
    max(abs(diff(f(w))))*fs, ...
    rad2deg(angle(vW(1)/vB(1))), ...
    abs(vW(1)) - abs(vB(1)), ...
    abs(vW(2)) - abs(vB(2)), ...
    abs(iW(1)) - abs(iB(1)), ...
    abs(iW(2)) - abs(iB(2)), ...
    pW - pB, ...
    qW - qB, ...
    pp(1), ...
    100*(res(vc, ww, vW) - res(vc, bw, vB)), ...
    100*(res(ic, ww, iW) - res(ic, bw, iB)), ...
    max(abs(dc(w) - mean(dc(b)))), ...
    max(abs(id(w) - mean(id(b)))), ...
    max(abs(iq(w) - mean(iq(b)))), ...
    log10((res(vc, ww, vW)/res(ic, ww, iW))/(res(vc, bw, vB)/res(ic, bw, iB))), ...
    max(abs(f(w) - fb))/(std(f(b)) + 1e-3), ...
    max(abs(V(w) - Vb))/(std(V(b)) + 1e-4)];
end
