function ev = disturbance_events(t0, G, v)
% DISTURBANCE_EVENTS  The ordinary (non-islanding) disturbances.
%   EV = DISTURBANCE_EVENTS(T0, G, V) returns eleven events, each with a NAME
%   and a SET function that applies it at time T0 (default 0.5 s) to a
%   parameter struct P. G and V are the operating irradiance (W/m2) and wind
%   speed (m/s), default 1000 and 12: the irradiance steps are to and from
%   60% of G, the wind step is to 75% of V. Most are events IEEE 1547-2018
%   requires a DER to ride through.
if nargin < 1 || isempty(t0), t0 = 0.5; end
if nargin < 2 || isempty(G), G = 1000; end
if nargin < 3 || isempty(v), v = 12; end
Gl = 0.6*G; vl = 0.75*v;
amp = @(a, d) struct('entity', 'Amplitude', 'type', 'Table of time-amplitude pairs', 'amp', [1 a 1], 'time', [0 t0 t0 + d]);
e = @(name, f) struct('name', name, 'set', f);
ev = [ ...
 e(sprintf('Irradiance %g to %g W/m2', G, Gl), @(P) setf(P, 'pv', struct('G0', G, 'G1', Gl, 'tStep', t0))), ...
 e(sprintf('Irradiance %g to %g W/m2', Gl, G), @(P) setf(P, 'pv', struct('G0', Gl, 'G1', G, 'tStep', t0))), ...
 e(sprintf('Wind %g to %g m/s', v, vl),        @(P) setf(P, 'wind', struct('v0', v, 'v1', vl, 'tStep', t0))), ...
 e('Load switched on (+6 kW)',     @(P) setf(P, 'event', struct('loadT', t0))), ...
 e('Capacitor switched on (5 kvar)', @(P) setf(P, 'event', struct('capT', t0))), ...
 e('Voltage sag to 0.7 pu, 0.5 s', @(P) setf(P, 'event', amp(0.7, 0.5))), ...
 e('Voltage sag to 0.5 pu, 0.2 s', @(P) setf(P, 'event', amp(0.5, 0.2))), ...
 e('Voltage swell to 1.15 pu, 0.5 s', @(P) setf(P, 'event', amp(1.15, 0.5))), ...
 e('Frequency ramp -2 Hz/s for 0.5 s', @(P) setf(P, 'event', struct('entity', 'Frequency', 'type', 'Ramp', 'rate', -2, 'timing', [t0 t0 + 0.5]))), ...
 e('Frequency ramp +2 Hz/s for 0.5 s', @(P) setf(P, 'event', struct('entity', 'Frequency', 'type', 'Ramp', 'rate', 2, 'timing', [t0 t0 + 0.5]))), ...
 e('Phase jump 20 deg',            @(P) setf(P, 'event', struct('entity', 'Phase', 'type', 'Step', 'step', 20, 'timing', [t0 1e6]))) ];
end

function P = setf(P, group, vals)
% Overwrite the named fields of P.(group).
f = fieldnames(vals);
for k = 1:numel(f), P.(group).(f{k}) = vals.(f{k}); end
if strcmp(group, 'wind') && isfield(vals, 'v0'), P.wind.wm0 = P.wind.lamOpt*P.wind.v0/P.wind.R; end
end
